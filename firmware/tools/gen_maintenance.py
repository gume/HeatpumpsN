"""Embed the maintenance page into the firmware.

    python tools/gen_maintenance.py

Writes include/hpn/maintenance_assets.h with gzip copies of src/maintenance.html
and data/js/hpnauth.js. The build's pre-script runs it on every local build;
the header is committed for PlatformIO Remote, which syncs only src/.
"""
import gzip
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = [("kMaintenanceHtmlGz", os.path.join(ROOT, "src", "maintenance.html")),
           ("kMaintenanceAuthJsGz", os.path.join(ROOT, "data", "js", "hpnauth.js"))]
OUT = os.path.join(ROOT, "include", "hpn", "maintenance_assets.h")


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:   # reproducible
        f.write(data)
    return buf.getvalue()


def render() -> str:
    out = ["#pragma once", "", "// Generated by tools/gen_maintenance.py: do not edit.", "",
           "#include <stdint.h>", ""]
    for name, path in SOURCES:
        data = gz(open(path, "rb").read())
        out.append(f"// {os.path.relpath(path, ROOT)} ({len(data)} bytes gzip)")
        out.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 20):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
        out.append("};")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render()
    if os.path.exists(OUT) and open(OUT).read() == text:
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print(f"[gen_maintenance] wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
